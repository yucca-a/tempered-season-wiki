const beta = (file, line) => ({ file, line });
const recipe = line => beta('scripts/um_preparedfoods.lua', line);
const ingredients = line => beta('init/init_food/init_crockpot.lua', line);

function food(prefab, title, english, nameLine, summary, sections, sources, configs = []) {
  return {
    id: prefab.replaceAll('_', '-'),
    category: 'new-items',
    prefab,
    icon: prefab,
    title,
    aliases: [english, prefab, '料理', '食谱'],
    summary,
    configs: ['newrecipes', ...configs],
    sections,
    sources: [
      ...sources,
      beta('modinfo.lua', 700),
      ingredients(605),
      { kind: 'cn', file: 'init/init_strings/init_names.lua', line: nameLine },
    ],
  };
}

